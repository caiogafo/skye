"""Leftovers of the old project name (Nimbus) after the rename to Skye (Req 23).

Scans every tracked or untracked-but-not-ignored text file, and every file or directory name,
for `nimbus` in any case. Allowed:

* the structure spec, which records the rename itself (it must name the old name);
* the codename tests, which check the umbrella watermark `nimbus` (documentation only).

Anything else that still says Nimbus was missed by the rename.
"""

from __future__ import annotations

import re
import subprocess

from tests.budget.measure import ROOT

OLD = re.compile(r"nimbus", re.IGNORECASE)
ALLOWED_PREFIXES = (
    ".kiro/specs/structure/",
    "docs/glossary.md",  # lists the umbrella watermark `nimbus`
    "tests/budget/test_codenames.py",
    "tests/budget/test_no_old_name.py",
)
SKIP_FILES = {"uv.lock"}  # regenerated by uv; a path dependency may carry the checkout name


def _files() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout.splitlines()
    return [f for f in out if not f.startswith(".serena/") and (ROOT / f).is_file()]


def _allowed(path: str) -> bool:
    return path.startswith(ALLOWED_PREFIXES) or path in SKIP_FILES


def test_no_file_or_directory_name_says_nimbus() -> None:
    bad = sorted({f for f in _files() if OLD.search(f) and not _allowed(f)})
    assert not bad, "Paths still named after the old project:\n  " + "\n  ".join(bad)


def test_no_file_content_says_nimbus() -> None:
    hits: list[str] = []
    for f in _files():
        if _allowed(f):
            continue
        try:
            text = (ROOT / f).read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue  # binary
        for n, line in enumerate(text.splitlines(), 1):
            if OLD.search(line):
                hits.append(f"{f}:{n}: {line.strip()[:100]}")
    assert not hits, "Occurrences of Nimbus/nimbus missed by the rename:\n  " + "\n  ".join(hits[:50])
